# --- "Best of" comparison with labels ---
CUSTOM_FUSED = ["kraken", "push_sync", "lamport", "2shot", "butterfly", "inplace"]
# inplace already in list
IN_TREE = ["nccl", "symm_1s", "symm_2s"]
FLASHINFER = ["fi_1shot", "fi_2shot"]

SHORT = {"lamport": "lam", "butterfly": "bfly", "symm_2s": "s2s", "symm_1s": "s1s",
         "push_sync": "ps", "kraken": "kr", "nccl": "nccl", "2shot": "2s",
         "inplace": "inp", "fi_1shot": "fi1", "fi_2shot": "fi2"}

def _best_of(data_key, methods, batch_filter):
    """Return [(b, best_time)] and [(b, best_method_name)] for given methods."""
    all_bs = sorted({b for m in METHODS for b, _ in DATA[data_key][m] if b in batch_filter})
    pts, names = [], []
    for b in all_bs:
        best_v, best_m = float("inf"), ""
        for m in methods:
            for bb, t in DATA[data_key].get(m, []):
                if bb == b and t < best_v:
                    best_v, best_m = t, m
        if best_v < float("inf"):
            pts.append((b, best_v))
            names.append(SHORT.get(best_m, best_m))
    return pts, names

def make_best_of_plot(batch_filter, title, filename, xticks):
    fig, axes = plt.subplots(len(HIDDEN_DIMS), len(WORLD_SIZES), figsize=(18, 22),
                             sharex=True)
    fig.suptitle(title, fontsize=15, fontweight="bold", y=0.998)

    BEST_ALL = CUSTOM_FUSED + IN_TREE
    groups = [
        ("NCCL + compiled rmsnorm", ["nccl"], "#888888", "D", ":"),
        ("best in-tree (symm_mem + compile)", IN_TREE, "#ff7f0e", "s", "--"),
        ("best FlashInfer", FLASHINFER, "#1f77b4", "P", "-"),
        ("best we can do", BEST_ALL, "#2ca02c", "o", "-"),
    ]

    for row_i, D in enumerate(HIDDEN_DIMS):
        for col_i, ws in enumerate(WORLD_SIZES):
            ax = axes[row_i, col_i]
            key = (ws, D)

            all_plot_pts = []
            for label, method_list, color, marker, ls in groups:
                pts, names = _best_of(key, method_list, batch_filter)
                if pts:
                    ax.plot([p[0] for p in pts], [p[1] for p in pts],
                            marker=marker, color=color, label=label,
                            linewidth=2.5, markersize=6, linestyle=ls, alpha=0.9)
                    for (bx, ty), nm in zip(pts, names):
                        ax.annotate(nm, (bx, ty), textcoords="offset points",
                                    xytext=(0, 7), fontsize=6, ha="center",
                                    color=color, fontweight="bold")
                    all_plot_pts.extend(pts)

            ax.set_xscale("log", base=2)
            ax.set_xticks(xticks)
            ax.get_xaxis().set_major_formatter(matplotlib.ticker.ScalarFormatter())
            ax.grid(True, alpha=0.3)
            if all_plot_pts:
                ax.set_ylim(bottom=0, top=max(p[1] for p in all_plot_pts) * 1.2)

            if row_i == 0:
                ax.set_title(f"world_size={ws}", fontsize=13, fontweight="bold")
            if col_i == 0:
                ax.set_ylabel(f"D={D}\nLatency (us)", fontsize=11)
            if row_i == len(HIDDEN_DIMS) - 1:
                ax.set_xlabel("Batch size (tokens)", fontsize=11)

    handles, labels = axes[0, 0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="upper center", ncol=2,
               fontsize=9, bbox_to_anchor=(0.5, 0.975), frameon=True)
    plt.tight_layout(rect=[0, 0, 1, 0.955])
    fig.savefig(filename, dpi=150, bbox_inches="tight")
    print(f"Saved to {filename}")
    plt.close(fig)

